const assert=require('node:assert/strict');
const {fit}=require('../autoscout/static/trajectory-fit.js');
const samples=Array.from({length:61},(_,i)=>{const t=i/60;return[t,.2+.15*t,.5-.4*t+.03*t*t+.45*t*t*t,.006,.006]});
const cubic=fit(samples,3),quadratic=fit(samples,2);
assert(cubic.rmse<1e-7&&cubic.curved);
assert(quadratic.rmse>cubic.rmse+.1);
assert.equal(cubic.points.length,49);
assert.equal(fit(samples.slice(0,4),3),null);
assert.equal(fit([[0,0,0,.01,.01],[1,1,1,.01,.01]],2),null);
const straight=samples.map(p=>[p[0],.2+.1*p[0],.4,.006,.006]);
assert(!fit(straight,2).curved);
const scaled=samples.map(([t,x,y,w,h])=>[t,x*.4+.1,y*.4+.2,w*.4,h*.4]);
assert(Math.abs(fit(scaled,2).rmse-quadratic.rmse)<1e-7);
console.log('Polynomial fit checks passed');
const {track}=require('../autoscout/static/trajectory-fit.js');
const detections=[0,.05,.1].map((t,i)=>({timestamp:t,camera_segment:0,objects:[{box:[.1+i*.002,.2,.11+i*.002,.21]}]}));
const original=JSON.stringify(detections),linked=track(detections,{gap:.15,distance:3});
assert.equal(linked.tracks.size,1);assert.equal(JSON.stringify(detections),original);
assert.equal(track(detections,{gap:.02,distance:3}).tracks.size,3);
assert.equal(track([...detections,{...detections[2],timestamp:.15,camera_segment:1}]).tracks.size,2);
console.log('Independent tracking checks passed');
